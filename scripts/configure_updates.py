"""Build-only config: never store the update signing PRIVATE key in Git.

Requirements:
  OLEA_UPDATER_PUBKEY  = public key generated by `npx tauri signer generate`
  GITHUB_REPOSITORY    = owner/repo, set automatically by GitHub Actions

The output src-tauri/tauri-updater.conf.json is git-ignored.
"""
import json
import os
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1]
public_key = os.environ.get("OLEA_UPDATER_PUBKEY", "").strip()
repository = os.environ.get("GITHUB_REPOSITORY", "").strip()
if not public_key or not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
    raise SystemExit("Imposta OLEA_UPDATER_PUBKEY e GITHUB_REPOSITORY prima di pubblicare una release firmata")
output = root / "src-tauri" / "tauri-updater.conf.json"
config = {
    "bundle": {"createUpdaterArtifacts": True},
    "plugins": {
        "updater": {
            "pubkey": public_key,
            "endpoints": [f"https://github.com/{repository}/releases/latest/download/latest.json"],
            "windows": {"installMode": "passive"}
        }
    }
}
output.write_text(json.dumps(config, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
print("Configurazione updater per il repository", repository)
